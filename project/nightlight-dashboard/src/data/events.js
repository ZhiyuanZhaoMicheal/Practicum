// Generate mock probability heatmap GeoJSON
// Replace this with actual model prediction outputs.
// Format expected: GeoJSON FeatureCollection with
// Point features, each having a `probability` (0–1)
// property and optionally a `buffer` (bool) property.
// =====================================================
function seededRandom(seed) {
  // Simple xorshift PRNG for reproducible mock data
  let s = seed
  return function () {
    s ^= s << 13; s ^= s >> 17; s ^= s << 5
    return (s >>> 0) / 4294967296
  }
}

export function generateMockProbabilityGeoJSON(event) {
  const rng = seededRandom(event.id.charCodeAt(0) * 31 + event.year)
  const [lng, lat] = event.center
  const features = []

  // Generate a 24x24 grid of prediction points over the study area
  const spread = 0.08
  const gridN   = 24

  for (let i = 0; i < gridN; i++) {
    for (let j = 0; j < gridN; j++) {
      const pLng = lng - spread + (i / (gridN - 1)) * spread * 2
      const pLat = lat - spread * 0.7 + (j / (gridN - 1)) * spread * 1.4

      // Base probability: slightly random
      let prob = 0.2 + rng() * 0.3

      // Boost probability near known facilities (simulates buffer zone signal)
      for (const fac of event.facilities) {
        const dlng = pLng - fac.coords[0]
        const dlat = pLat - fac.coords[1]
        const dist  = Math.sqrt(dlng * dlng + dlat * dlat)
        const radius = 0.01 // ~1km in degrees
        if (dist < radius) {
          prob = Math.max(prob, fac.probability * (1 - dist / radius) + 0.2 * rng())
        }
      }

      prob = Math.min(0.99, Math.max(0.01, prob))

      features.push({
        type: 'Feature',
        geometry: { type: 'Point', coordinates: [pLng, pLat] },
        properties: {
          probability: parseFloat(prob.toFixed(3)),
          // Flag pixels inside any buffer zone
          inBuffer: prob > 0.6,
        },
      })
    }
  }

  return { type: 'FeatureCollection', features }
}

// =====================================================
// Buffer circle GeoJSON (approximate, for display)
// =====================================================
export function generateBufferGeoJSON(event) {
  const features = []

  for (const fac of event.facilities) {
    const radiusM = BUFFER_RADII[fac.type] ?? 750
    // Convert radius to approximate degrees
    const radiusDeg = radiusM / 111320
    const steps = 48
    const coords = []

    for (let i = 0; i <= steps; i++) {
      const angle = (i / steps) * 2 * Math.PI
      coords.push([
        fac.coords[0] + radiusDeg * Math.cos(angle),
        fac.coords[1] + radiusDeg * Math.sin(angle) * 0.85, // lat correction
      ])
    }

    features.push({
      type: 'Feature',
      geometry: { type: 'Polygon', coordinates: [coords] },
      properties: {
        name: fac.name,
        type: fac.type,
        probability: fac.probability,
        radiusM,
      },
    })
  }

  return { type: 'FeatureCollection', features }
}

